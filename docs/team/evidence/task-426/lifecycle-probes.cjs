'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { tracker, finalize } = require('./lifecycle.cjs');
(async () => {
  const work = tracker(), calls = [];
  let release;
  const handler = work.run(() => new Promise(resolve => { release = () => { calls.push('handler settled'); resolve(); }; }));
  await Promise.resolve();
  await assert.rejects(work.join(5), /Mutable work join deadline/);
  assert.equal(work.size, 1);
  let published;
  const receipt = { invocation: 'offline-only-unique', sourceSHA: 'c8672a17ea9be27014cbdcf14e6e472fb2d8b70f', sourceDigest: 'offline-probe-not-runtime' };
  await finalize({ steps: [['release', () => release()], ['join', () => work.join(50)], ['disconnect', () => { assert.equal(work.size, 0); calls.push('disconnect'); }]], receipt: () => receipt, publish: result => { published = result; } });
  await handler;
  assert.deepEqual(calls, ['handler settled', 'disconnect']);
  assert.equal(published.invocation, receipt.invocation);
  assert.equal(published.sourceSHA, receipt.sourceSHA);
  const primary = new Error('original checkout failure');
  let reported = '';
  await assert.rejects(finalize({ primary, steps: [['cleanup', () => calls.push('cleaned')]], receipt: () => receipt, publish: () => { throw new Error('ENOSPC'); }, report: message => { reported = message; } }), error => error === primary);
  assert.match(reported, /ENOSPC/); assert.match(reported, /original checkout failure/); assert.match(reported, /"ok":true/);
  const initialization = new Error('initialization failed');
  await assert.rejects(finalize({ primary: initialization, steps: [['disconnect initialized resources', () => calls.push('init cleanup')]], receipt: () => ({ ...receipt, rows: [] }), publish: result => { published = result; } }), error => error === initialization);
  assert.equal(published.status, 'FAILED'); assert.match(published.originalFailure, /initialization failed/);
  assert.deepEqual(published.rows, []); assert(calls.includes('init cleanup'));
  const stuck = tracker(); stuck.run(() => new Promise(() => {}));
  let joined = false, disconnected = false;
  await assert.rejects(finalize({ steps: [['join', async () => { await stuck.join(5); joined = true; }], ['disconnect', () => { if (!joined) throw new Error('SKIPPED pending work'); disconnected = true; }]], receipt: () => receipt, publish: result => { published = result; } }), /Owned cleanup incomplete/);
  assert.equal(disconnected, false); assert.equal(published.status, 'CLEANUP_FAILED'); assert.equal(published.cleanup[1].ok, false);
  const source = fs.readFileSync('tixmoapi2/tests/qualification/orders-http-abort.local.ts', 'utf8');
  assert(source.indexOf('await Promise.race([terminal.promise') < source.indexOf('      gate.resolve();'));
  assert(source.indexOf("['join admitted mutable work'") < source.indexOf("['Prisma disconnect'"));
  assert.match(source, /flag: 'wx'/); assert.match(source, /\['diff', '--quiet', 'HEAD'/);
  assert.match(source, /phase.inflight = inflight/);
  console.log('PASS pending handler joins before disconnect; stuck handler prevents disconnect; first error survives ENOSPC with cleanup diagnostics; initialization failure cleanup/receipt; invocation and source binding; ACK ordering. Offline only, no sockets/services.');
})().catch(error => { console.error(error); process.exitCode = 1; });
