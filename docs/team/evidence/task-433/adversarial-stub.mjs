import assert from 'node:assert/strict';
import {compose} from '../../../../scripts/market-composition.mjs';
const base={versions:{node:'stub',npm:'stub'},capture:()=>({source:'candidate'})};
let stored;
const spoof=async contract=>({contract,close:async()=>{},run:async()=>({status:0,stdout:'raw',stderr:'',index:999,phase:'wrong',command:'not-executed',args:['spoof'],started:'forged'})});
await compose({...base,openAudit:spoof,openLocal:spoof,persist:async m=>stored=m});
assert.equal(stored.receipts.length,12);
assert(stored.receipts.every(r=>r.index===999&&r.phase==='wrong'&&r.command==='not-executed'&&r.started==='forged'));
console.log('REPRODUCED finding1: adapter result overwrites canonical index/phase/command/args/timestamps in all12 receipts');
let changed=false, localRuns=0, saved;
const audit=async contract=>({contract,close:async()=>{changed=true;},run:async()=>({status:0,stdout:'',stderr:''})});
const local=async contract=>({contract,close:async()=>{},run:async()=>{localRuns++;return{status:0,stdout:'',stderr:''};}});
await assert.rejects(compose({...base,capture:()=>({source:changed?'changed':'candidate'}),openAudit:audit,openLocal:local,persist:async m=>saved=m}),/Candidate changed/);
assert.equal(localRuns,1);assert.equal(saved.qualification,'INCOMPLETE');
console.log('REPRODUCED finding2: source mutation during audit teardown permits first local run before invalidation');
let rejectedManifest,closed=0;
const rejects=async contract=>({contract,close:async()=>{closed++;},run:async()=>{throw Error('adapter rejected');}});
await assert.rejects(compose({...base,openAudit:rejects,openLocal:local,persist:async m=>rejectedManifest=m}),/adapter rejected/);
assert.equal(closed,1);assert.equal(rejectedManifest.failure,'adapter rejected');assert.equal(rejectedManifest.receipts.length,0);
console.log('PASS rejected run closes phase once and persists incomplete failure; all probes in-memory/no connections');
